/**
 * ищем количество сестёр у произвольного брата
 *
 * @param int $n Количество сестёр у Алисы (кроме неё)
 * @param int $m Количество братьев
 * @return int|null Количество сестёр у любого брата, либо null при некорректном введении данных
 */
function getSistersOfBrother(int $n, int $m): ?int
{
    // Проверка на неотрицательные значения
    if ($n < 0 || $m <= 0) {
        return null; // Некорректные данные
    }

    // Расчет количества сестёр у любого брата
    return $n + 1;
}